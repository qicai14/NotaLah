import { createReadStream } from 'node:fs';
import { mkdir, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { Readable } from 'node:stream';
import { AwsClient } from 'aws4fetch';
import { consumeOrThrow, UsageLimitError } from '../features/usage/service';
import { env } from './env';

/**
 * Object storage behind the asset routes (D54). The local driver serves dev and tests. The R2 driver (S3-compatible)
 * implements the same three methods and streams every byte through the server: no presigned GET or PUT URLs and no
 * browser-direct uploads, so each operation passes `metered` (R34, D57). Uploads are one PutObject, never multipart.
 */
interface StoredRead {
  /** Whole object size; `start`..`end` (inclusive) is what `stream` yields, and `partial` says a range was applied. */
  size: number;
  start: number;
  end: number;
  partial: boolean;
  stream: Readable;
}

/** A single `bytes=` range against `size` bytes, or null when absent, malformed or multi-range (served whole). */
export function parseRange(
  header: string | undefined,
  size: number,
): { start: number; end: number } | 'unsatisfiable' | null {
  const m = /^bytes=(\d*)-(\d*)$/.exec(header ?? '');
  if (!m || (m[1] === '' && m[2] === '')) return null;
  let start: number;
  let end: number;
  if (m[1] === '') {
    start = Math.max(size - Number(m[2]), 0);
    end = size - 1;
  } else {
    start = Number(m[1]);
    end = m[2] === '' ? size - 1 : Math.min(Number(m[2]), size - 1);
  }
  return start >= size || start > end ? 'unsatisfiable' : { start, end };
}

export interface Storage {
  put(key: string, body: Buffer): Promise<void>;
  /** The object, or the part a `Range` header asks for, as a stream; null when it does not exist, `{ unsatisfiable: size }` when the range lies outside it. */
  read(key: string, range?: string): Promise<StoredRead | { unsatisfiable: number } | null>;
  /** Idempotent: a missing object is not an error. */
  remove(key: string): Promise<void>;
}

/** Keys are generated by the server (`i/<uuid>.webp`); anything else never reaches the disk. */
const KEY = /^[a-z]\/[0-9a-f-]{36}\.[a-z0-9]{2,5}$/;

function assertKey(key: string) {
  if (!KEY.test(key)) throw new Error('Invalid storage key');
}

function localStorageDriver(root: string): Storage {
  const file = (key: string) => {
    assertKey(key);
    return path.join(root, ...key.split('/'));
  };
  return {
    async put(key, body) {
      const target = file(key);
      await mkdir(path.dirname(target), { recursive: true });
      await writeFile(target, body);
    },
    async read(key, header) {
      const target = file(key);
      const info = await stat(target).catch((err: NodeJS.ErrnoException) => {
        if (err.code === 'ENOENT') return null;
        throw err;
      });
      if (!info) return null;
      const range = parseRange(header, info.size);
      if (range === 'unsatisfiable') return { unsatisfiable: info.size };
      const { start, end } = range ?? { start: 0, end: info.size - 1 };
      return { size: info.size, start, end, partial: range !== null, stream: createReadStream(target, { start, end }) };
    },
    async remove(key) {
      await rm(file(key), { force: true });
    },
  };
}

interface R2Config {
  accountId: string;
  accessKeyId: string;
  secretAccessKey: string;
  bucket: string;
}

const R2_TIMEOUT_MS = { put: 60_000, read: 30_000, remove: 15_000 };

/**
 * Cloudflare R2 over its S3 API (D60), signed with aws4fetch. Single PutObject, ranged GetObject streamed straight to
 * the caller, DeleteObject. No retries: `metered` counts one op per call, so a hidden retry would undercount (D60).
 * `fetchImpl` is injectable for tests.
 */
export function r2StorageDriver(cfg: R2Config, fetchImpl: typeof fetch = fetch): Storage {
  const aws = new AwsClient({
    accessKeyId: cfg.accessKeyId,
    secretAccessKey: cfg.secretAccessKey,
    service: 's3',
    region: 'auto',
  });
  const base = `https://${cfg.accountId}.r2.cloudflarestorage.com/${cfg.bucket}/`;
  /** Signs and sends; the timer covers the wait for response headers, not the body stream that follows. */
  const call = async (key: string, init: RequestInit, ms: number) => {
    assertKey(key);
    const ctl = new AbortController();
    const timer = setTimeout(() => ctl.abort(), ms);
    try {
      return await fetchImpl(await aws.sign(base + key, init), { signal: ctl.signal });
    } finally {
      clearTimeout(timer);
    }
  };
  const drop = (res: Response) => void res.body?.cancel().catch(() => {});
  const fail = (op: string, res: Response) => {
    drop(res);
    return new Error(`R2 ${op} failed with status ${res.status}`);
  };
  return {
    async put(key, body) {
      const res = await call(
        key,
        { method: 'PUT', body: new Uint8Array(body.buffer as ArrayBuffer, body.byteOffset, body.byteLength) },
        R2_TIMEOUT_MS.put,
      );
      if (!res.ok) throw fail('put', res);
      drop(res);
    },
    async read(key, header) {
      const asked = /^bytes=(\d*)-(\d*)$/.test(header ?? '') && header !== 'bytes=-' ? header : undefined;
      const res = await call(key, { method: 'GET', headers: asked ? { Range: asked } : {} }, R2_TIMEOUT_MS.read);
      if (res.status === 404) {
        drop(res);
        return null;
      }
      if (res.status === 416) {
        drop(res);
        const total = /\/(\d+)$/.exec(res.headers.get('content-range') ?? '')?.[1];
        if (total === undefined) throw new Error('R2 read failed: 416 without a Content-Range size');
        return { unsatisfiable: Number(total) };
      }
      if (!res.ok || !res.body) throw fail('read', res);
      let info: { size: number; start: number; end: number; partial: boolean };
      if (res.status === 206) {
        const m = /^bytes (\d+)-(\d+)\/(\d+)$/.exec(res.headers.get('content-range') ?? '');
        if (!m) throw fail('read', res);
        info = { size: Number(m[3]), start: Number(m[1]), end: Number(m[2]), partial: true };
      } else {
        const size = Number(res.headers.get('content-length'));
        if (!Number.isFinite(size) || size < 0) throw fail('read', res);
        info = { size, start: 0, end: size - 1, partial: false };
      }
      return { ...info, stream: Readable.fromWeb(res.body as never) };
    },
    async remove(key) {
      const res = await call(key, { method: 'DELETE' }, R2_TIMEOUT_MS.remove);
      if (!res.ok && res.status !== 404) throw fail('remove', res);
      drop(res);
    },
  };
}

/**
 * Counts every write as an R2 Class A operation and every read as Class B (R34, D57); deletes are free on R2 and not
 * counted. Past a cap, or with `UPLOADS_DISABLED`, the call throws `UsageLimitError` before touching storage.
 */
export function metered(inner: Storage): Storage {
  return {
    ...inner,
    async put(key, body) {
      if (env.UPLOADS_DISABLED) throw new UsageLimitError('Uploads are turned off');
      await consumeOrThrow('class_a', 'Monthly upload limit reached');
      await inner.put(key, body);
    },
    async read(key, range) {
      await consumeOrThrow('class_b', 'Monthly upload limit reached');
      return inner.read(key, range);
    },
  };
}

export const storage: Storage = metered(
  env.STORAGE_DRIVER === 'r2'
    ? r2StorageDriver({
        accountId: env.R2_ACCOUNT_ID!,
        accessKeyId: env.R2_ACCESS_KEY_ID!,
        secretAccessKey: env.R2_SECRET_ACCESS_KEY!,
        bucket: env.R2_BUCKET!,
      })
    : localStorageDriver(env.STORAGE_DIR),
);
