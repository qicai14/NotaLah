"""Assemble the Chapter 4 sections into CHAPTER4.md with figures and tables numbered in reading order.

Captions are written as "*Figure 4.x: ...*" / "*Table 4.x: ...*". Inside the paragraphs that follow a
caption, "Figure 4.x" / "Table 4.x" mean that caption. "Figure [[png_stem]]" refers to any figure by
its image file name, and "Table [[next]]" / "Figure [[next]]" to the next caption of that kind. Explicit numbers already in the text (Figure 4.1, Tables 4.1-4.22) are kept, and
counting continues after them.
Usage: python build_chapter.py
"""
import re
from pathlib import Path

HERE = Path(__file__).parent
PARTS = ["4.1_introduction.md", "4.2.1_use_cases.md", "4.2.3_class_activity_sequence.md",
         "4.3_database_design.md", "4.4_interface_design.md", "4.5_test_cases.md"]


def build() -> str:
    text = "\n\n".join((HERE / p).read_text(encoding="utf8").strip() for p in PARTS)
    fig = max([int(n) for n in re.findall(r"Figure 4\.(\d+)", text)] or [0])
    tab = max([int(n) for n in re.findall(r"Table 4\.(\d+)", text)] or [0])
    by_stem, out, last = {}, [], {"Figure": None, "Table": None}
    pending = {"Figure": [], "Table": []}  # output line indexes waiting for the next caption number
    lines = text.split("\n")
    for i, line in enumerate(lines):
        line = re.sub(r"^!\[(Figure|Table) 4\.x: ", "![", line)  # alt text precedes its caption; drop the number
        cap = re.match(r"\*(Figure|Table) 4\.x:", line)
        if cap:
            kind = cap.group(1)
            if kind == "Figure":
                fig += 1
                last[kind] = fig
                img = re.search(r"png/([\w.-]+)\.png", lines[i - 2] if i >= 2 else "")
                if img:
                    by_stem[img.group(1)] = fig
            else:
                tab += 1
                last[kind] = tab
            for j in pending[kind]:
                out[j] = out[j].replace(f"{kind} [[next]]", f"{kind} 4.{last[kind]}")
            pending[kind] = []
        for kind in ("Figure", "Table"):
            if last[kind] is not None:
                line = line.replace(f"{kind} 4.x", f"{kind} 4.{last[kind]}")
        for kind in ("Figure", "Table"):
            if f"{kind} [[next]]" in line:
                pending[kind].append(len(out))
        out.append(line)
    result = "\n".join(out)
    result = re.sub(r"Figure \[\[([\w.-]+)\]\]", lambda m: f"Figure 4.{by_stem[m.group(1)]}", result)
    assert "4.x" not in result, "unnumbered caption or reference left"
    return result


if __name__ == "__main__":
    chapter = build()
    (HERE / "CHAPTER4.md").write_text(
        "<!-- Generated by build_chapter.py from the 4.*.md sections; edit those, not this file. -->\n\n" + chapter,
        encoding="utf8")
    print(f"figures: {len(re.findall(r'^\*Figure', chapter, re.M))}, tables: {len(re.findall(r'^\*Table', chapter, re.M))}")
