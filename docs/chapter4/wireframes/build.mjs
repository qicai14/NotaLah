// Renders the PARP wireframes (Chapter 4.4, v3) to svg/ and png/, and writes INDEX.md.
// Usage: node build.mjs [name-filter]   (needs `npm ci` and `npx playwright install chromium` once)
//
// Screens live in screens.mjs (review order sets the NN_ number), shared styles and parts in lib.mjs.
// Each screen is laid out as HTML, serialised to a vector SVG by svg.mjs (text stays <text>, so Figma
// imports editable layers), then that SVG is rasterised to png/ so the report shows exactly what Figma gets.
import { chromium } from 'playwright';
import { mkdirSync, readFileSync, readdirSync, unlinkSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { css } from './lib.mjs';
import { screens } from './screens.mjs';
import { domToSvg, lofiIcons } from './svg.mjs';

const named = screens.map((s, i) => ({ ...s, file: `${String(i + 1).padStart(2, '0')}_${s.id.replaceAll('_', '-')}` }));
const only = process.argv[2];

const outSvg = new URL('./svg/', import.meta.url), outPng = new URL('./png/', import.meta.url);
for (const d of [outSvg, outPng]) {
  mkdirSync(d, { recursive: true });
  if (!only) for (const f of readdirSync(d)) if (/\.(png|svg)$/.test(f)) unlinkSync(new URL(f, d));
}

const browser = await chromium.launch();
for (const s of named) {
  if (only && !s.file.includes(only)) continue;
  const viewport = s.m ? { width: 390, height: 844 } : { width: 1440, height: 900 };
  const page = await browser.newPage({ viewport, deviceScaleFactor: 2 });
  await page.setContent(`<!doctype html><html lang="en"><head><meta charset="utf-8"><title>${s.t}</title><style>${css}</style></head><body>${s.html}</body></html>`);
  await page.evaluate(lofiIcons);
  const svg = (await page.evaluate(domToSvg)).replace('<defs>', `<title>${s.t.replace(/&/g, '&amp;').replace(/</g, '&lt;')}</title>\n<defs>`);
  writeFileSync(fileURLToPath(new URL(`${s.file}.svg`, outSvg)), svg);
  await page.setContent(`<!doctype html><html><head><style>body{margin:0}svg{display:block}</style></head><body>${svg.replace(/^<\?xml[^>]*>/, '')}</body></html>`);
  await page.screenshot({ path: fileURLToPath(new URL(`${s.file}.png`, outPng)) });
  await page.close();
}
await browser.close();

/* ------------------------------------------------------------------ ALL_SCREENS.svg (every screen on one canvas) */
if (!only) {
  const GAP = 80, COLS = 4, LABEL = 56;
  let x = 0, y = 0, rowH = 0, col = 0, maxW = 0;
  const parts = [];
  for (const s of named) {
    const src = readFileSync(fileURLToPath(new URL(`${s.file}.svg`, outSvg)), 'utf8').replace(/^<\?xml[^>]*>\s*/, '');
    const [, w, h] = src.match(/width="(\d+)" height="(\d+)"/).map(Number);
    if (col === COLS) { x = 0; y += rowH + GAP + LABEL; rowH = 0; col = 0; }
    const p = `s${s.file.slice(0, 2)}-`; // keep ids unique across screens
    const body = src.replace(/id="([^"]+)"/g, `id="${p}$1"`).replace(/url\(#([^)]+)\)/g, `url(#${p}$1)`)
      .replace(/^<svg /, `<svg x="${x}" y="${y + LABEL}" `);
    parts.push(`<g id="screen-${s.file}"><text x="${x}" y="${y + 36}" font-size="28" font-weight="700" fill="#1c1c1c">${s.file.slice(0, 2)} ${s.t.replace(/&/g, '&amp;').replace(/</g, '&lt;')}</text>${body}</g>`);
    x += w + GAP; rowH = Math.max(rowH, h); maxW = Math.max(maxW, x - GAP); col++;
  }
  const H = y + rowH + LABEL;
  writeFileSync(fileURLToPath(new URL('ALL_SCREENS.svg', outSvg)), `<?xml version="1.0" encoding="UTF-8"?>\n<svg xmlns="http://www.w3.org/2000/svg" width="${maxW}" height="${H}" viewBox="0 0 ${maxW} ${H}" font-family="Segoe UI, Arial, sans-serif">\n<rect width="${maxW}" height="${H}" fill="#f4f4f4"/>\n${parts.join('\n')}\n</svg>\n`);
}

/* ------------------------------------------------------------------ INDEX.md */
const cell = (t) => String(t).replaceAll('|', '\\|');
const fresh = named.filter((s) => s.v3 === 'new').length;
const index = `# PARP wireframes v3 (Chapter 4.4)

Generated by \`build.mjs\` from \`screens.mjs\`; do not edit by hand. ${named.length} screens
(${named.filter((s) => !s.m).length} desktop at 1440 x 900, ${named.filter((s) => s.m).length} mobile at 390 x 844), ${fresh} of them new in v3.

- Vector files for Figma: \`svg/NN_name.svg\` (text is real \`<text>\`, shapes are rect/path, icons are vector groups,
  main regions are named \`<g id>\` layers). Import with File > Import or drag the files onto a Figma page.
- Report images: \`png/NN_name.png\` (2x), rasterised from the same SVG.
- v3 changes for every screen: lower fidelity (greyscale boxes, lorem ipsum for descriptive copy, crossed boxes for
  images), "For You" renamed **Feed**, "Contacts only" renamed **Friends only**, editor top bar gains **Share** (R30).

| No. | Screen (SVG) | PNG | Covers | Purpose | New in v3 |
|---|---|---|---|---|---|
${named.map((s) => `| ${s.file.slice(0, 2)} | [${cell(s.t)}](svg/${s.file}.svg)${s.m ? ' (mobile)' : ''} | [png](png/${s.file}.png) | ${cell(s.refs)} | ${cell(s.p)} | ${s.v3 === 'new' ? '**Yes**' : s.v3 ? cell(s.v3) : 'No'} |`).join('\n')}
`;
if (!only) writeFileSync(fileURLToPath(new URL('./INDEX.md', import.meta.url)), index);
console.log(`rendered ${only ? 'filtered' : named.length} wireframes`);
