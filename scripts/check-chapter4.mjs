import { readFileSync } from 'node:fs';
import path from 'node:path';

const PARTS = [
  '4.1_introduction.md',
  '4.2.1_use_cases.md',
  '4.2.3_class_activity_sequence.md',
  '4.3_database_design.md',
  '4.4_interface_design.md',
  '4.5_test_cases.md',
];
const HEADER = '<!-- Generated by build_chapter.py from the 4.*.md sections; edit those, not this file. -->\n\n';
const KINDS = ['Figure', 'Table'];

const read = (file) => readFileSync(file, 'utf8').replace(/\r\n?/g, '\n');
const maxNum = (text, kind) =>
  Math.max(0, ...[...text.matchAll(new RegExp(String.raw`${kind} 4\.(\d+)`, 'g'))].map((m) => +m[1]));
const replaceAll = (s, from, to) => s.split(from).join(to);

export function build(dir) {
  const text = PARTS.map((p) => read(path.join(dir, p)).trim()).join('\n\n');
  const count = { Figure: maxNum(text, 'Figure'), Table: maxNum(text, 'Table') };
  const byStem = {};
  const out = [];
  const last = { Figure: null, Table: null };
  const pending = { Figure: [], Table: [] };
  const lines = text.split('\n');
  lines.forEach((raw, i) => {
    let line = raw.replace(/^!\[(Figure|Table) 4\.x: /, '![');
    const cap = line.match(/^\*(Figure|Table) 4\.x:/);
    if (cap) {
      const kind = cap[1];
      last[kind] = ++count[kind];
      if (kind === 'Figure') {
        const img = (i >= 2 ? lines[i - 2] : '').match(/png\/([\w.-]+)\.png/);
        if (img) byStem[img[1]] = last[kind];
      }
      for (const j of pending[kind]) out[j] = replaceAll(out[j], `${kind} [[next]]`, `${kind} 4.${last[kind]}`);
      pending[kind] = [];
    }
    for (const kind of KINDS)
      if (last[kind] !== null) line = replaceAll(line, `${kind} 4.x`, `${kind} 4.${last[kind]}`);
    for (const kind of KINDS) if (line.includes(`${kind} [[next]]`)) pending[kind].push(out.length);
    out.push(line);
  });
  const result = out.join('\n').replace(/Figure \[\[([\w.-]+)\]\]/g, (_, stem) => {
    if (!(stem in byStem)) throw new Error(`no figure for image ${stem}`);
    return `Figure 4.${byStem[stem]}`;
  });
  if (result.includes('4.x')) throw new Error('unnumbered caption or reference left');
  return HEADER + result;
}

export function firstDiff(expected, actual) {
  if (expected === actual) return '';
  const a = expected.split('\n');
  const b = actual.split('\n');
  const n = a.findIndex((l, i) => l !== b[i]);
  const i = n === -1 ? a.length : n;
  return `line ${i + 1}: expected ${JSON.stringify(a[i] ?? '(end of file)')}, found ${JSON.stringify(b[i] ?? '(end of file)')}`;
}

export function problems(dir, file = path.join(dir, 'CHAPTER4.md')) {
  let built;
  try {
    built = build(dir);
  } catch (e) {
    return [`cannot build CHAPTER4.md: ${e.message}`];
  }
  const diff = firstDiff(built, read(file));
  return diff
    ? [
        `CHAPTER4.md is stale (${diff}); run python docs/chapter4/build_chapter.py (mirrored by scripts/check-chapter4.mjs; change both)`,
      ]
    : [];
}

if (import.meta.main) {
  const root = path.resolve(import.meta.dirname, '..');
  const [dir = path.join(root, 'docs/chapter4'), file] = process.argv.slice(2);
  const found = problems(dir, file);
  for (const p of found) console.error(`chapter4: ${p}`);
  process.exit(found.length ? 1 : 0);
}
