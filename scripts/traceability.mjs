import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

// Survey finding -> FR/NFR -> TC -> UAT result, from docs/testing/traceability-map.json and the 4.5 Pass and Completed columns.
const cells = (line) =>
  line
    .split('|')
    .slice(1, -1)
    .map((c) => c.trim());

export function matrix(map, md) {
  const rows = md
    .split('\n')
    .filter((l) => l.startsWith('| '))
    .map(cells);
  const tcs = rows.filter((r) => /^[A-Z]+-TC\d+$/.test(r[0]));
  const uat = Object.fromEntries(rows.filter((r) => /^UAT-[A-Z]\d+$/.test(r[0])).map((r) => [r[0], r[6] || 'pending']));
  const gaps = [];
  const lines = ['| Requirement | Survey finding | TCs passing | UAT result |', '| --- | --- | --- | --- |'];
  for (const [req, [finding, keys, tasks]] of Object.entries(map)) {
    const mine = tcs.filter(([id]) => keys.some((k) => id === k || id.startsWith(`${k}-`)));
    const pass = mine.filter((r) => r[5] === 'Pass').length;
    const failing = mine.filter((r) => r[5] === 'Fail').map((r) => r[0]);
    if (!pass) gaps.push(`${req}: no passing TC (${keys.join(', ')}; ${mine.length} matched)`);
    if (failing.length) gaps.push(`${req}: failing TC ${failing.join(', ')}`);
    const result = tasks.map((t) => `${t}: ${uat[t] ?? 'unknown'}`).join('; ') || 'none';
    lines.push(`| ${req} | ${finding} | ${pass} of ${mine.length} (${keys.join(', ')}) | ${result} |`);
  }
  return { md: lines.join('\n') + '\n', gaps };
}

if (import.meta.main) {
  const root = path.resolve(import.meta.dirname, '..');
  const map = JSON.parse(readFileSync(path.join(root, 'docs/testing/traceability-map.json'), 'utf8'));
  const { md, gaps } = matrix(map, readFileSync(path.join(root, 'docs/chapter4/4.5_test_cases.md'), 'utf8'));
  writeFileSync(
    path.join(root, 'docs/testing/traceability.md'),
    `# Traceability matrix\n\nGenerated by scripts/traceability.mjs; edit docs/testing/traceability-map.json, not this file.\n\n${md}`,
  );
  for (const g of gaps) console.error(`traceability: ${g}`);
  process.exit(gaps.length ? 1 : 0);
}
